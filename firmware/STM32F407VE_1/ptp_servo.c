/* PTP clock servo of the Sync Hub - C port of ptp_sim.py (method M2 = M1 + AI bias correction).
 *  1. lucky-packet filter: sliding minimum (O(1) monotonic deque) of forward and reverse delays
 *  2. AI: a 13-16-8-1 MLP (with an out-of-distribution guard) estimates the residual bias of that filter from 12 queue statistics,
 *     low-pass filtered, gated (|bias| > 0.5 us) and clipped (+-5 us) so it can never make
 *     light-load operation worse (verified on unseen traffic in simulation)
 *  3. PI servo -> frequency correction (ppb) written to the ETH PTP addend register (ptp_hw.c)  */
#include "mathlite.h"
#include <string.h>
#include "ptp_servo.h"
#include "mlp_weights.h"          /* generated by 07_IA/A3_Servo_PTP_ML/export_mlp_c.py */

#define WMAX 128
#define FW 32
static servo_cfg_t cfg;
static double I_term, ema_bias;
typedef struct { int64_t v[WMAX]; uint32_t k[WMAX]; int h, n; uint32_t cnt; int W; } monomin_t;
static monomin_t mf, mr, f32m, r32m;
static double ring_f[FW], ring_r[FW]; static int ring_i, ring_n;

static void mm_init(monomin_t *m, int W) { memset(m, 0, sizeof *m); m->W = W; }
static int64_t mm_push(monomin_t *m, int64_t x)
{   /* deque stored in a circular buffer: indices h .. h+n-1 */
    while (m->n && m->v[(m->h + m->n - 1) % WMAX] >= x) m->n--;
    int t = (m->h + m->n) % WMAX; m->v[t] = x; m->k[t] = m->cnt; m->n++;
    while (m->k[m->h] + (uint32_t)m->W <= m->cnt) { m->h = (m->h + 1) % WMAX; m->n--; }
    m->cnt++;
    return m->v[m->h];
}
void servo_init(const servo_cfg_t *c)
{
    cfg = *c; I_term = 0; ema_bias = 0; ring_i = ring_n = 0;
    mm_init(&mf, c->W); mm_init(&mr, c->W); mm_init(&f32m, FW); mm_init(&r32m, FW);
}
static int cmpd(const void *a, const void *b) { double d = *(const double*)a - *(const double*)b; return (d > 0) - (d < 0); }
#include <stdlib.h>
static double median(const double *x, int n) { double t[FW]; memcpy(t, x, n * sizeof(double)); qsort(t, n, sizeof(double), cmpd); return (n & 1) ? t[n/2] : 0.5*(t[n/2-1] + t[n/2]); }

static float mlp_forward(const float *x)
{
    float h1[MLP_H1], h2[MLP_H2], xin[MLP_NIN];
    for (int i = 0; i < MLP_NIN; i++) xin[i] = (x[i] - MLP_MU[i]) / MLP_SD[i];
    for (int j = 0; j < MLP_H1; j++) { float s = MLP_B1[j]; for (int i = 0; i < MLP_NIN; i++) s += xin[i] * MLP_W1[i][j]; h1[j] = s > 0 ? s : 0; }
    for (int j = 0; j < MLP_H2; j++) { float s = MLP_B2[j]; for (int i = 0; i < MLP_H1; i++) s += h1[i] * MLP_W2[i][j]; h2[j] = s > 0 ? s : 0; }
    float o = MLP_B3[0]; for (int i = 0; i < MLP_H2; i++) o += h2[i] * MLP_W3[i][0];
    return o;                                                         /* bias estimate, microseconds */
}

double servo_update(const ptp_exchange_t *e, double *offset_ns, double *ai_bias_ns)
{
    const double Ts = 0.125;
    int64_t fwd = e->t2 - e->t1, rev = e->t4 - e->t3;
    double z1 = 0.5 * (double)(mm_push(&mf, fwd) - mm_push(&mr, rev));          /* lucky-packet offset, ns */
    /* ---- 12 observable queue statistics over the last 32 exchanges (us) ---- */
    double fm = (double)mm_push(&f32m, fwd), rm = (double)mm_push(&r32m, rev);
    ring_f[ring_i] = (double)fwd; ring_r[ring_i] = (double)rev; ring_i = (ring_i + 1) % FW; if (ring_n < FW) ring_n++;
    double df[FW], dr[FW], sf = 0, sr = 0, qf = 0, qr = 0, l4f = 0, l4r = 0;
    for (int i = 0; i < ring_n; i++) { df[i] = (ring_f[i] - fm) * 1e-3; dr[i] = (ring_r[i] - rm) * 1e-3; sf += df[i]; sr += dr[i]; }
    double mfv = sf / ring_n, mrv = sr / ring_n;
    for (int i = 0; i < ring_n; i++) { qf += (df[i]-mfv)*(df[i]-mfv); qr += (dr[i]-mrv)*(dr[i]-mrv); }
    int nl = ring_n < 4 ? ring_n : 4;
    for (int k = 1; k <= nl; k++) { int i = (ring_i - k + FW) % FW; l4f += df[i]; l4r += dr[i]; }
    float x[MLP_NIN] = { (float)((fwd - fm) * 1e-3), (float)((rev - rm) * 1e-3), (float)(((fwd - fm) - (rev - rm)) * 1e-3),
                         (float)mfv, (float)mrv, (float)ml_sqrt(qf / ring_n), (float)ml_sqrt(qr / ring_n),
                         (float)median(df, ring_n), (float)median(dr, ring_n), (float)(l4f / nl), (float)(l4r / nl),
                         (float)((0.5 * (fwd + rev) - 0.5 * (fm + rm)) * 1e-3), 0.0f /* reserved */ };
    double bias_ns = 0;
    if (cfg.ai_enable) {
        /* out-of-distribution guard: if any input is > OOD_Z standard deviations away from the
           training data the model is not trusted and the servo falls back to the classic filter */
        int ood = 0;
        for (int i = 0; i < 12; i++) if (ml_fabsf((x[i] - MLP_MU[i]) / MLP_SD[i]) > cfg.ood_z) ood = 1;
        double b = ood ? 0.0 : (double)mlp_forward(x) * 1e3;
        ema_bias = (1 - cfg.ema) * ema_bias + cfg.ema * b;
        bias_ns = ema_bias;
        if (ml_fabs(bias_ns) < cfg.gate_us * 1e3) bias_ns = 0;
        if (bias_ns >  cfg.clip_us * 1e3) bias_ns =  cfg.clip_us * 1e3;
        if (bias_ns < -cfg.clip_us * 1e3) bias_ns = -cfg.clip_us * 1e3;
    }
    double zc = (z1 - bias_ns) * 1e-9;                                       /* seconds */
    I_term += cfg.ki * zc / Ts;
    double u = cfg.kp * zc / Ts + I_term;                                    /* fractional frequency */
    if (offset_ns) *offset_ns = zc * 1e9;
    if (ai_bias_ns) *ai_bias_ns = bias_ns;
    return u * 1e9;                                                          /* ppb */
}
